// pipeline/serialize.ts — 存档 → 数据AI可见的紧凑状态文本
//
// 数据AI不看世界书、不直读存档 JSON；这里把它需要的最小状态摘要渲染成文本。
import type { Game } from '../core/schema';
import { 算力上限, 生效属性, 世界状态, 陷落度阶段名 } from '../engine/engine';

/** 数据AI 用的紧凑状态摘要（占位符 {{状态}} 的展开内容） */
export function serialize数据AI(g: Game): string {
  const 行: string[] = [];
  行.push(`当前时刻：${g.时刻.当前时刻}`);
  行.push(`位置：${g.位置.区域} · ${g.位置.当前}`);
  行.push(`陷落度：${g.时钟.维尔伦陷落度}/6（${陷落度阶段名(g.时钟.维尔伦陷落度)}）｜肃清进度：${g.时钟.教会肃清进度}/3`);
  行.push(`算力：${g.算力.当前算力}/${算力上限(g)}（速率 ${g.算力.速率}/小时，累计消耗 ${g.算力.累计消耗}，世界状态：${世界状态(g)}）`);

  const 主 = g.主角;
  const 临时描述 = 主.临时加成.length
    ? '，临时：' + 主.临时加成.map(b => `${b.属性}${b.值 > 0 ? '+' : ''}${b.值}(${b.来源},剩${b.剩余分钟}分)`).join('、')
    : '';
  行.push(`主角：力${生效属性(g, '力量')} 敏${生效属性(g, '敏捷')} 体${生效属性(g, '体质')} 智${生效属性(g, '智力')}${临时描述}`);
  if (主.状态) 行.push(`主角状态：${主.状态}`);
  if (主.技能.length) 行.push(`主角技能：${主.技能.map(s => `${s.名称}(${s.等阶})`).join('、')}`);
  const 装备 = Object.entries(主.装备).filter(([, v]) => v).map(([k, v]) => `${k}:${v}`).join('、');
  if (装备) 行.push(`主角装备：${装备}`);
  行.push(`精练师等级：${主.精练师等级}｜已解锁知识库：${主.已解锁知识库.join('、')}`);

  if (g.物品.length) {
    行.push('物品：' + g.物品.map(i => `${i.名称}×${i.数量}(${i.类型}${i.槽 ? '/' + i.槽 : ''}${i.持有者 !== '主角' ? ',' + i.持有者 : ''})`).join('、'));
  } else {
    行.push('物品：（无）');
  }

  const 已遇见 = (Object.entries(g.生物) as [string, Game['生物'][keyof Game['生物']]][]).filter(([, b]) => b.已遇见);
  if (已遇见.length) {
    行.push('已遇见人物：' + 已遇见.map(([名, b]) => {
      const 临时 = b.临时加成.length ? `,临时:${b.临时加成.map(x => `${x.属性}${x.值 > 0 ? '+' : ''}${x.值}`).join('/')}` : '';
      return `${名}(${b.立场},${b.状态 || '未知'}${临时})`;
    }).join('、'));
  } else {
    行.push('已遇见人物：（无）');
  }

  return 行.join('\n');
}
