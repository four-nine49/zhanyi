// pipeline/settle.ts — 艾瑟兰战役变更包结算（严格按《变量设计.md》§四顺序）
//
// 原则：最佳努力逐条应用——单条非法只丢该条记日志，不连坐其他条目。
import type { Game } from '../core/schema';
import type { 变更包 } from './contract';
import {
  结算时间, 结算时钟, 结算推演, 结算属性, 结算主角状态, 结算临时加成新增, 结算临时加成移除,
  结算物品新增, 结算物品移除, 结算物品数量, 结算装备变更,
  结算技能新增, 结算技能提升, 结算技能移除, 结算生物, 结算精练师等级,
} from '../engine/engine';

export interface 结算结果 {
  g: Game;
  日志: string[];              // 本回合所有结算动作的可读记录
  丢弃: string[];              // 被丢弃的条目及原因
}

/** 结算一整个变更包，返回新 Game 与日志 */
export function settle(旧g: Game, 包: 变更包): 结算结果 {
  let g: Game = JSON.parse(JSON.stringify(旧g));   // 深拷贝，避免污染原档
  const 日志: string[] = [];
  const 丢弃: string[] = [];

  // ── 1. 时间结算（最先）──
  const 时间结果 = 结算时间(g, 包.当前时刻);
  g = 时间结果.g;
  const r = 时间结果.结果;
  if (r.Δt > 0) {
    日志.push(`时间流逝 ${r.Δt} 分钟 → ${r.新当前时刻}`);
    if (r.算力恢复 > 0) 日志.push(`算力恢复 +${r.算力恢复}（当前 ${g.算力.当前算力}）`);
    if (r.陷落度自动推进 > 0) 日志.push(`陷落度自动推进 +${r.陷落度自动推进}（当前 ${g.时钟.维尔伦陷落度}/6）`);
    if (r.智力成长 > 0) 日志.push(`智力随时间成长 +${r.智力成长}（当前 ${g.主角.属性.智力}，上限 14）`);
    if (r.到期加成.length > 0) 日志.push(`临时加成到期移除: ${r.到期加成.join('、')}`);
  }

  // ── 2. 位置 ──
  if (包.位置) {
    if (包.位置.当前 != null) { g.位置.当前 = 包.位置.当前; 日志.push(`位置 → ${包.位置.当前}`); }
    if (包.位置.区域 != null) { g.位置.区域 = 包.位置.区域; 日志.push(`区域 → ${包.位置.区域}`); }
  }

  // ── 3. 时钟申报 ──
  if (包.时钟?.维尔伦陷落度) {
    const 旧 = g.时钟.维尔伦陷落度;
    g = 结算时钟(g, '维尔伦陷落度', 包.时钟.维尔伦陷落度);
    日志.push(`陷落度申报 +${包.时钟.维尔伦陷落度}（${旧} → ${g.时钟.维尔伦陷落度}）`);
  }
  if (包.时钟?.教会肃清进度) {
    const 旧 = g.时钟.教会肃清进度;
    g = 结算时钟(g, '教会肃清进度', 包.时钟.教会肃清进度);
    日志.push(`肃清进度申报 +${包.时钟.教会肃清进度}（${旧} → ${g.时钟.教会肃清进度}）`);
  }

  // ── 4. 推演 ──
  if (包.推演) {
    const 结果 = 结算推演(g, 包.推演.名称, 包.推演.档);
    if (结果.结果.成交) {
      g = 结果.g;
      日志.push(`推演成交「${包.推演.名称}」档${包.推演.档}，扣费 ${结果.结果.实付算力}（剩余 ${g.算力.当前算力}，累计 ${g.算力.累计消耗}）`);
      if (结果.结果.触发裂隙) {
        日志.push(`⚠ 累计消耗跨过 250，世界进入【裂隙】：魔物全属性 +1（${(结果.结果.裂隙强化 || []).join('、') || '无魔物在档'}）`);
      }
    } else {
      丢弃.push(`推演「${包.推演.名称}」驳回：${结果.结果.驳回原因}`);
    }
  }

  // ── 5. 属性 ──
  if (包.属性) {
    const 待结算 = { ...包.属性 };
    // 智力禁令：智力由脚本接管（AI 不得申报），只丢该字段不连坐
    if (待结算.智力 != null) {
      丢弃.push('属性「智力」变动被拒（智力由脚本接管，数据AI 不得申报）');
      delete 待结算.智力;
    }
    if (Object.keys(待结算).length > 0) {
      const 旧属性 = { ...g.主角.属性 };
      g = 结算属性(g, '主角', 待结算);
      const 变化 = Object.entries(待结算)
        .filter(([, v]) => v != null && v !== 0)
        .map(([k, v]) => `${k} ${旧属性[k as keyof typeof 旧属性]}→${g.主角.属性[k as keyof typeof 旧属性]}(${v! > 0 ? '+' : ''}${v})`)
        .join('、');
      if (变化) 日志.push(`属性变化: ${变化}`);
    }
  }

  // ── 6. 主角状态（自由文本；"健康" 即恢复正常）──
  if (包.主角状态 != null) {
    const 旧 = g.主角.状态 || '（无）';
    g = 结算主角状态(g, 包.主角状态);
    日志.push(`主角状态 ${旧} → ${包.主角状态}`);
  }

  // ── 7. 临时加成 ──
  if (包.临时加成新增) {
    for (const 加成 of 包.临时加成新增) {
      g = 结算临时加成新增(g, '主角', { 属性: 加成.属性, 值: 加成.值, 剩余分钟: 加成.持续分钟, 来源: 加成.来源 });
      日志.push(`临时加成新增「${加成.来源}」${加成.属性}${加成.值 > 0 ? '+' : ''}${加成.值}（${加成.持续分钟}分钟）`);
    }
  }
  if (包.临时加成移除) {
    for (const 来源 of 包.临时加成移除) {
      g = 结算临时加成移除(g, '主角', 来源);
      日志.push(`临时加成移除「${来源}」`);
    }
  }

  // ── 8. 物品/装备 ──
  if (包.物品新增) {
    for (const 物品 of 包.物品新增) {
      g = 结算物品新增(g, 物品);
      日志.push(`物品新增「${物品.名称}」×${物品.数量}（${物品.类型}，持有者:${物品.持有者}；每件独立编号）`);
    }
  }
  if (包.物品移除) {
    for (const 名称 of 包.物品移除) {
      g = 结算物品移除(g, 名称);
      日志.push(`物品移除「${名称}」`);
    }
  }
  if (包.物品数量) {
    for (const [名称, 变化] of Object.entries(包.物品数量)) {
      const 前 = g.物品.length;
      const 新g = 结算物品数量(g, 名称, 变化);
      if (新g === g && 变化 !== 0) {
        丢弃.push(`物品「${名称}」数量变化 ${变化} 未生效（同名物品不足或无模板）`);
        continue;
      }
      g = 新g;
      日志.push(`物品「${名称}」数量 ${变化 > 0 ? '+' : ''}${变化}（现存 ${g.物品.filter(i => i.名称 === 名称).length} 件）`);
    }
  }
  if (包.装备变更) {
    const 结果 = 结算装备变更(g, 包.装备变更.人物, 包.装备变更.槽, 包.装备变更.物品);
    if (结果.成功) {
      g = 结果.g;
      const 槽值 = (包.装备变更.人物 === '主角' ? g.主角.装备 : g.生物.爱丽丝.装备)?.[包.装备变更.槽];
      const 显示 = 槽值 ? (g.物品.find(i => i.编号 === 槽值)?.名称 ?? 槽值) + `(#${槽值})` : '(卸下)';
      日志.push(`装备变更 ${包.装备变更.人物}.${包.装备变更.槽} → ${显示}`);
    } else {
      丢弃.push(`装备变更驳回：${结果.原因}`);
    }
  }

  // ── 9. 技能 ──
  if (包.技能新增) {
    for (const 技 of 包.技能新增) {
      g = 结算技能新增(g, 技.人物 as any, { 名称: 技.名称, 等阶: 技.等阶, 描述: 技.描述 });
      日志.push(`技能新增 ${技.人物}「${技.名称}」(${技.等阶})`);
    }
  }
  if (包.技能提升) {
    for (const 提 of 包.技能提升) {
      const 结果 = 结算技能提升(g, 提.人物 as any, 提.名称);
      if (结果.成功) { g = 结果.g; 日志.push(`技能提升 ${提.人物}「${提.名称}」`); }
      else 丢弃.push(`技能提升驳回 ${提.人物}「${提.名称}」：已是大师或不存在`);
    }
  }
  if (包.技能移除) {
    for (const 移 of 包.技能移除) {
      g = 结算技能移除(g, 移.人物 as any, 移.名称);
      日志.push(`技能移除 ${移.人物}「${移.名称}」`);
    }
  }

  // ── 10. 精练师等级 ──
  if (包.精练师等级) {
    const 旧 = g.主角.精练师等级;
    g = 结算精练师等级(g, 包.精练师等级);
    if (g.主角.精练师等级 !== 旧) 日志.push(`精练师等级 ${旧} → ${g.主角.精练师等级}`);
  }

  // ── 11. 生物 ──
  if (包.生物) {
    const 关系白名单 = ['路人', '相识', '熟人', '恋人', '灵魂的另一半'];
    for (const [名, 更新原] of Object.entries(包.生物)) {
      if (!(名 in g.生物)) { 丢弃.push(`生物「${名}」不在建档列表`); continue; }
      let 更新 = 更新原;
      if (更新.和主角的关系 != null && !关系白名单.includes(更新.和主角的关系)) {
        丢弃.push(`生物「${名}」和主角的关系取值非法（${更新.和主角的关系}），已忽略该字段`);
        更新 = { ...更新, 和主角的关系: undefined };
      }
      const 旧已遇见 = g.生物[名 as keyof Game['生物']].已遇见;
      g = 结算生物(g, 名 as keyof Game['生物'], 更新);
      const 新对象 = g.生物[名 as keyof Game['生物']];
      const 变化: string[] = [];
      if (更新.已遇见 === true && !旧已遇见) 变化.push('初遇');
      if (更新.状态 != null) 变化.push(`状态→"${更新.状态}"`);
      if (更新.和主角的关系 != null) 变化.push(`关系→${更新.和主角的关系}`);
      if (更新.属性) 变化.push(`属性${JSON.stringify(更新.属性)}`);
      if (变化.length > 0) 日志.push(`生物「${名}」${变化.join('、')}`);
    }
  }

  return { g, 日志, 丢弃 };
}
